// Checks Arcade game files against the format in src/arcade/format.js, including the plug-in types
// in src/arcade/types/*.check.js and their games in src/arcade/extra/*.js, and the learning paths.
// With every file valid, it also rewrites src/arcade/catalog.index.js: the catalog list without the
// rounds, which the Arcade shows before it loads any game (see src/arcade/catalog.js).
// Usage: node scripts/check-arcade.mjs [file …]   (no arguments: every category and extra file)
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { basename, dirname, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { check } from '../src/arcade/format.js'
import { PATHS } from '../src/arcade/paths.js'
import { DEMOS } from '../src/arcade/demos.js'

const CATEGORIES = ['limits', 'integration', 'datamodel', 'service', 'sales', 'cpq', 'deployment']
const INDEX = resolve('src/arcade/catalog.index.js')
const list = (dir, suffix) => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(suffix)).sort().map((f) => resolve(dir, f)) : [])
const load = async (file) => (await import(pathToFileURL(file).href)).default

const extra = {}
for (const file of list(resolve('src/arcade/types'), '.check.js')) extra[basename(file, '.check.js')] = await load(file)

const all = !process.argv.slice(2).length
const files = all
  ? [...list(resolve('src/arcade/games'), '.js'), ...list(resolve('src/arcade/extra'), '.js')]
  : process.argv.slice(2).map((f) => resolve(f))

const seen = new Set()
const index = {}
let problems = 0
for (const file of files) {
  const data = await load(file)
  const isExtra = basename(dirname(file)) === 'extra'
  const category = isExtra ? { id: `extra/${basename(file, '.js')}`, title: 'x', icon: 'x', blurb: 'x', games: data.games } : data
  const errors = check(category, seen, extra)
  if (isExtra) data.games?.forEach((g) => { if (!CATEGORIES.includes(g.category)) errors.push(`${g.id}: unknown category ${g.category}`) })
  const rounds = category.games?.reduce((n, g) => n + (g.rounds?.length ?? 0), 0) ?? 0
  console.log(`${errors.length ? '✗' : '✓'} ${category.id}: ${category.games?.length ?? 0} games, ${rounds} rounds`)
  errors.forEach((e) => console.log(`   ${e}`))
  problems += errors.length

  // What the catalog shows of each game: everything but the rounds and what the rounds need.
  const meta = (g) => ({ ...(isExtra ? { category: g.category } : {}), id: g.id, title: g.title, blurb: g.blurb, type: g.type, level: g.level, n: g.rounds?.length ?? 0 })
  const key = `${basename(dirname(file))}/${basename(file, '.js')}`
  index[key] = isExtra ? { games: (data.games ?? []).map(meta) } : { id: data.id, title: data.title, icon: data.icon, blurb: data.blurb, games: (data.games ?? []).map(meta) }
}

if (all) {
  // Learning paths may only use games that exist.
  const ids = new Set([...seen, ...Object.values(DEMOS).map((d) => d.id), ...CATEGORIES.flatMap((c) => [`${c}-speed-run`, `${c}-hot-seat`])])
  for (const p of PATHS) {
    const errors = []
    if (p.games.length < 10 || p.games.length > 15) errors.push(`needs 10–15 games, has ${p.games.length}`)
    if (new Set(p.games).size !== p.games.length) errors.push('a game appears twice')
    p.games.filter((id) => !ids.has(id)).forEach((id) => errors.push(`unknown game ${id}`))
    console.log(`${errors.length ? '✗' : '✓'} path ${p.id}: ${p.games.length} games`)
    errors.forEach((e) => console.log(`   ${e}`))
    problems += errors.length
  }

  // The catalog index, one game per line.
  const games = (list) => list.map((g) => `      ${JSON.stringify(g)},`).join('\n')
  const body = Object.entries(index).map(([key, { games: list, ...rest }]) => {
    const head = Object.entries(rest).map(([k, v]) => `    ${k}: ${JSON.stringify(v)},\n`).join('')
    return `  ${JSON.stringify(key)}: {\n${head}    games: [\n${games(list)}\n    ],\n  },`
  })
  const text = `// GENERATED by \`node scripts/check-arcade.mjs\` from src/arcade/games/*.js and src/arcade/extra/*.js.
// The catalog list without the rounds, so the Arcade can show it before loading any game content
// (see catalog.js). Don't edit by hand: run the script after adding or changing a game.
export default {
${body.join('\n')}
}
`
  const old = existsSync(INDEX) ? readFileSync(INDEX, 'utf8') : ''
  if (problems) console.log(`✗ catalog.index.js not updated: fix the problems above first${old === text ? '' : ' (it is out of date)'}`)
  else if (old === text) console.log('✓ catalog.index.js is up to date')
  else {
    writeFileSync(INDEX, text)
    console.log('↻ catalog.index.js updated')
  }
}
process.exit(problems ? 1 : 0)
